package com.paysentry.mockbank.service;

import java.math.BigDecimal;
import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.UUID;
import java.util.concurrent.ConcurrentHashMap;

import javax.annotation.PostConstruct;

import org.springframework.beans.factory.annotation.Value;
import org.springframework.http.HttpEntity;
import org.springframework.http.HttpHeaders;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.stereotype.Service;
import org.springframework.web.client.RestTemplate;

import com.paysentry.mockbank.dto.BackendEventPayload;
import com.paysentry.mockbank.dto.MockAccountResponse;
import com.paysentry.mockbank.dto.MockLienResponse;
import com.paysentry.mockbank.dto.MockTransactionResponse;
import com.paysentry.mockbank.dto.SimulationScenario;

@Service
public class MockBankService {

    private static final BigDecimal INITIAL_BALANCE = new BigDecimal("250000.00");

    private final Map<String, AccountState> accounts = new ConcurrentHashMap<>();
    private final RestTemplate restTemplate;
    private final String backendBaseUrl;
    private final String mockBankKey;

    public MockBankService(
            RestTemplate restTemplate,
            @Value("${paysentry.backend.base-url}") String backendBaseUrl,
            @Value("${paysentry.backend.mock-key}") String mockBankKey) {
        this.restTemplate = restTemplate;
        this.backendBaseUrl = backendBaseUrl;
        this.mockBankKey = mockBankKey;
    }

    @PostConstruct
    void initializeDemoAccount() {
        accounts.put("PS-10001", new AccountState("PS-10001"));
    }

    public synchronized MockAccountResponse getAccount(String accountId) {
        return toAccountResponse(getOrCreateAccount(accountId));
    }

    public synchronized List<MockTransactionResponse> getTransactions(String accountId) {
        return new ArrayList<>(getOrCreateAccount(accountId).transactions);
    }

    public synchronized MockLienResponse getLien(String accountId) {
        AccountState account = getOrCreateAccount(accountId);
        if (account.lienHistory.isEmpty()) {
            MockLienResponse response = new MockLienResponse();
            response.setCurrentLienAmount(account.lienAmount);
            response.setPreviousLienAmount(BigDecimal.ZERO);
            response.setReason("No lien changes simulated.");
            response.setReference("N/A");
            response.setTimestamp(account.updatedAt);
            return response;
        }
        return account.lienHistory.get(0);
    }

    public synchronized Map<String, Object> simulate(String accountId, SimulationScenario scenario) {
        AccountState account = getOrCreateAccount(accountId);
        BackendEventPayload payload = createPayload(account, scenario);
        updateMockState(account, payload);

        HttpHeaders headers = new HttpHeaders();
        headers.setContentType(MediaType.APPLICATION_JSON);
        headers.set("X-Mock-Bank-Key", mockBankKey);
        ResponseEntity<Object> backendResponse = restTemplate.postForEntity(
                backendBaseUrl + "/api/internal/mock-events",
                new HttpEntity<>(payload, headers),
                Object.class);

        Map<String, Object> result = new LinkedHashMap<>();
        result.put("scenario", scenario.name());
        result.put("mockAccount", toAccountResponse(account));
        result.put("backendRiskAssessment", backendResponse.getBody());
        result.put("warning", "This was generated by the local Mock Banking API; no real bank was contacted.");
        return result;
    }

    private BackendEventPayload createPayload(AccountState account, SimulationScenario scenario) {
        BackendEventPayload payload = basePayload(account);
        if (scenario == SimulationScenario.NORMAL_ACTIVITY) {
            configureTransaction(payload, "1500.00", "City Mart", "Bengaluru", "Known Android device", false, false);
        } else if (scenario == SimulationScenario.LARGE_TRANSACTION) {
            configureTransaction(payload, "125000.00", "Crypto Wallet Services", "Remote location",
                    "Unrecognized Android device", true, true);
        } else if (scenario == SimulationScenario.NEW_DEVICE_TRANSACTION) {
            configureTransaction(payload, "45000.00", "Online Merchant", "Bengaluru", "New Android device", true,
                    false);
        } else if (scenario == SimulationScenario.NEW_LOCATION_TRANSACTION) {
            configureTransaction(payload, "18000.00", "Travel Merchant", "Unrecognized location",
                    "Known Android device", false, true);
        } else if (scenario == SimulationScenario.LIEN_CREATE) {
            configureLien(payload, account, new BigDecimal("60000.00"), "Unverified lien hold", "", false);
        } else if (scenario == SimulationScenario.LIEN_INCREASE) {
            configureLien(payload, account, account.lienAmount.add(new BigDecimal("35000.00")),
                    "Repeated unexplained lien update", "", false);
        } else if (scenario == SimulationScenario.DEVICE_CHANGE) {
            payload.setEventType("DEVICE_CHANGE");
            payload.setDevice("New Android device");
            payload.setNewDevice(true);
        } else if (scenario == SimulationScenario.LOCATION_CHANGE) {
            payload.setEventType("LOCATION_CHANGE");
            payload.setLocation("Unrecognized location");
            payload.setNewLocation(true);
        }
        return payload;
    }

    private BackendEventPayload basePayload(AccountState account) {
        BackendEventPayload payload = new BackendEventPayload();
        payload.setEventId("MOCK-" + UUID.randomUUID());
        payload.setAccountId(account.accountId);
        payload.setOccurredAt(LocalDateTime.now());
        payload.setTotalBalance(account.totalBalance);
        payload.setAvailableBalance(account.availableBalance);
        return payload;
    }

    private void configureTransaction(
            BackendEventPayload payload,
            String amount,
            String receiver,
            String location,
            String device,
            boolean newDevice,
            boolean newLocation) {
        payload.setEventType("TRANSACTION");
        payload.setAmount(new BigDecimal(amount));
        payload.setReceiver(receiver);
        payload.setLocation(location);
        payload.setDevice(device);
        payload.setNewDevice(newDevice);
        payload.setNewLocation(newLocation);
    }

    private void configureLien(
            BackendEventPayload payload,
            AccountState account,
            BigDecimal lienAmount,
            String reason,
            String reference,
            boolean expectedActivity) {
        payload.setEventType("LIEN_CHANGE");
        payload.setPreviousLienAmount(account.lienAmount);
        payload.setLienAmount(lienAmount);
        payload.setLienReason(reason);
        payload.setTransactionReference(reference);
        payload.setExpectedActivity(expectedActivity);
        payload.setAvailableBalance(account.totalBalance.subtract(lienAmount));
    }

    private void updateMockState(AccountState account, BackendEventPayload payload) {
        if ("TRANSACTION".equals(payload.getEventType())) {
            account.totalBalance = nonNegative(account.totalBalance.subtract(payload.getAmount()));
            account.availableBalance = nonNegative(account.availableBalance.subtract(payload.getAmount()));
            payload.setTotalBalance(account.totalBalance);
            payload.setAvailableBalance(account.availableBalance);

            MockTransactionResponse transaction = new MockTransactionResponse();
            transaction.setTransactionId(payload.getEventId());
            transaction.setAmount(payload.getAmount());
            transaction.setReceiver(payload.getReceiver());
            transaction.setLocation(payload.getLocation());
            transaction.setDevice(payload.getDevice());
            transaction.setTimestamp(payload.getOccurredAt());
            account.transactions.add(0, transaction);
        }
        if ("LIEN_CHANGE".equals(payload.getEventType())) {
            account.lienAmount = payload.getLienAmount();
            account.availableBalance = nonNegative(account.totalBalance.subtract(account.lienAmount));
            payload.setAvailableBalance(account.availableBalance);

            MockLienResponse lien = new MockLienResponse();
            lien.setCurrentLienAmount(payload.getLienAmount());
            lien.setPreviousLienAmount(payload.getPreviousLienAmount());
            lien.setReason(payload.getLienReason());
            lien.setReference(payload.getTransactionReference());
            lien.setTimestamp(payload.getOccurredAt());
            account.lienHistory.add(0, lien);
        }
        account.updatedAt = payload.getOccurredAt();
    }

    private AccountState getOrCreateAccount(String accountId) {
        return accounts.computeIfAbsent(accountId, AccountState::new);
    }

    private MockAccountResponse toAccountResponse(AccountState account) {
        MockAccountResponse response = new MockAccountResponse();
        response.setAccountId(account.accountId);
        response.setTotalBalance(account.totalBalance);
        response.setAvailableBalance(account.availableBalance);
        response.setLienAmount(account.lienAmount);
        response.setCurrency("INR");
        response.setUpdatedAt(account.updatedAt);
        return response;
    }

    private BigDecimal nonNegative(BigDecimal value) {
        return value.max(BigDecimal.ZERO);
    }

    private static class AccountState {
        private final String accountId;
        private BigDecimal totalBalance = INITIAL_BALANCE;
        private BigDecimal availableBalance = INITIAL_BALANCE;
        private BigDecimal lienAmount = BigDecimal.ZERO;
        private LocalDateTime updatedAt = LocalDateTime.now();
        private final List<MockTransactionResponse> transactions = new ArrayList<>();
        private final List<MockLienResponse> lienHistory = new ArrayList<>();

        private AccountState(String accountId) {
            this.accountId = accountId;
        }
    }
}
